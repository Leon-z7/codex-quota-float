'use strict';
// Optional: PLAYWRIGHT_MODULE points to Playwright; CHROMIUM_MODULE to @sparticuz/chromium.
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { pathToFileURL } = require('node:url');
(async () => {
  const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
  const serverChromium = process.env.CHROMIUM_MODULE ? (await import(pathToFileURL(process.env.CHROMIUM_MODULE).href)).default : null;
  const browser = await chromium.launch(serverChromium ? {executablePath:await serverChromium.executablePath(),args:serverChromium.args,headless:true} : {headless:true});
  const out = path.resolve(__dirname,'../../artifacts'); fs.mkdirSync(out,{recursive:true});
  const page = await browser.newPage({viewport:{width:376,height:800},deviceScaleFactor:2});
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  await page.addInitScript(() => {
    let settings={style:'apple',theme:'light',alwaysOnTop:true,refreshSeconds:60};
    const callbacks={}; const resets=new Date(); resets.setDate(resets.getDate()+1);resets.setHours(14,4,0,0);
    const snapshot={planType:'plus',updatedAt:new Date().toISOString(),buckets:[{limitId:'codex',limitName:'Codex',primary:{usedPercent:25,windowDurationMins:300,resetsAt:resets.getTime()/1000},secondary:{usedPercent:58,windowDurationMins:10080,resetsAt:Date.now()/1000+200000}}]};
    window.fixture=snapshot;window.sizes=[];
    window.quotaApp={bootstrap:async()=>({snapshot,status:{level:'ok',message:'已连接'},settings}),refresh:async()=>{window.refreshCount=(window.refreshCount||0)+1;return snapshot}, updateSettings:async patch=>{settings={...settings,...patch};return settings},resize:async size=>{window.sizes.push(size)},hide:async()=>{},quit:async()=>{},onSnapshot:cb=>callbacks.snapshot=cb,onStatus:cb=>callbacks.status=cb,onSettings:cb=>callbacks.settings=cb};
    window.previewTest=callbacks;
  });
  await page.goto(pathToFileURL(path.resolve(__dirname,'../src/renderer/index.html')).href);
  await page.waitForFunction(()=>document.querySelector('.meter-value')?.textContent==='75%');
  const settle=()=>page.evaluate(()=>new Promise(resolve=>requestAnimationFrame(()=>requestAnimationFrame(resolve))));
  const fit=async()=>{await settle();const size=await page.evaluate(()=>sizes.at(-1));await page.setViewportSize({width:typeof size==='number'?({apple:376,pill:540,fluent:404}[await page.getAttribute('body','data-style')]):size.width,height:typeof size==='number'?size:size.height});await settle();};
  for(const [style,width] of [['apple',376],['pill',540],['fluent',404]]) {
    await page.setViewportSize({width,height:800});
    if(style!=='apple') await page.selectOption('#style',style);
    await fit();
    assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
    await page.locator('#toggle').click();await fit();
    assert.equal(await page.locator('#settings').isVisible(),true);
  }
  await page.selectOption('#style','mini');await fit();
  assert.equal(await page.locator('#shell').isVisible(),false);
  assert.equal(await page.locator('#mini-percent').textContent(),'75%');
  assert.equal(await page.locator('#mini-time').textContent(),'14:04');
  assert.equal(await page.locator('#mini-more circle').count(),3);
  assert.equal(await page.locator('#mini-percent').evaluate(e=>getComputedStyle(e).fontWeight),'400');
  const geometry=await page.evaluate(()=>{const r=id=>{const x=document.querySelector(id).getBoundingClientRect();return {x:x.x,y:x.y,width:x.width,height:x.height,right:x.right,bottom:x.bottom}};return {bar:r('#mini-bar'),percent:r('#mini-percent'),time:r('#mini-time'),more:r('#mini-more'),size:sizes.at(-1)}});
  assert.ok(geometry.percent.height>geometry.time.height);
  assert.ok(geometry.more.x-geometry.time.right<=8.5);
  assert.ok(geometry.size.width<180 && geometry.size.height===60);
  await page.screenshot({path:path.join(out,'mini-light.png')});
  await page.locator('#mini-more').click();await fit();
  assert.equal(await page.locator('#shell').isVisible(),true);
  assert.equal(await page.locator('.meter-value').nth(1).textContent(),'42%');
  assert.match(await page.locator('.reset-at').nth(1).textContent(),/\d{4}年\d+月\d+日 \d{2}:\d{2}/);
  await page.locator('#refresh').click(); assert.equal(await page.evaluate(()=>refreshCount),1);
  await page.locator('#top').uncheck();
  await page.selectOption('#theme','dark');await fit();
  assert.equal(await page.getAttribute('body','data-theme'),'dark');
  await page.screenshot({path:path.join(out,'mini-details-dark.png')});
  await page.keyboard.press('Escape');await fit();
  assert.equal(await page.locator('#mini-more').getAttribute('aria-expanded'),'false');
  await page.screenshot({path:path.join(out,'mini-dark.png')});
  await page.locator('#mini-more').focus();await page.keyboard.press('Enter');await fit();
  await page.selectOption('#theme','light');await fit();
  await page.screenshot({path:path.join(out,'mini-details-light.png')});
  await page.evaluate(()=>window.dispatchEvent(new Event('blur')));await fit();
  assert.equal(await page.locator('#shell').isVisible(),false);
  await page.evaluate(()=>previewTest.snapshot({...fixture,updatedAt:new Date(Date.now()-600000).toISOString(),buckets:[{limitId:'codex',primary:{usedPercent:99.6,windowDurationMins:300,resetsAt:null}}]}));await fit();
  assert.equal(await page.locator('#mini-percent').textContent(),'0.4%');
  assert.equal(await page.locator('#mini-time').textContent(),'--:--');
  assert.equal(await page.getAttribute('body','data-stale'),'true');
  await page.evaluate(()=>previewTest.status({level:'error',message:'连接断开'}));
  assert.match(await page.getAttribute('#mini-bar','title'),/连接中断/);
  await page.evaluate(()=>previewTest.snapshot({...fixture,buckets:[{limitId:'codex',secondary:fixture.buckets[0].secondary}]}));await fit();
  assert.equal(await page.locator('#mini-percent').textContent(),'—%');
  await page.evaluate(()=>previewTest.snapshot({...fixture,buckets:[]}));await fit();
  assert.equal(await page.locator('#mini-percent').textContent(),'—%');
  await page.locator('#mini-more').click();await fit();
  await page.selectOption('#style','apple');await fit();
  assert.equal(await page.locator('#mini-bar').isVisible(),false);
  assert.equal(await page.locator('#shell').isVisible(),true);
  assert.deepEqual(errors,[]);
  fs.writeFileSync(path.join(out,'ui-check.json'),JSON.stringify({passed:true,geometry,checks:['all existing styles','mini collapsed content and dimensions','regular enlarged percentage','tight time/menu gap','weekly full reset date','refresh','always on top setting','light/dark','Escape/Enter/blur','missing short window','fractional usage','stale/error/empty','switch back'],errors},null,2));
  await browser.close(); console.log('UI_BROWSER_PASS');
})().catch(e=>{console.error(e);process.exit(1)});
